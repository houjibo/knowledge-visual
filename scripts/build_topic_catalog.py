#!/usr/bin/env python3
"""Generate a local topic search catalog from site pages and navigation links."""
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import sys
from urllib.parse import unquote, urlsplit

sys.dont_write_bytecode = True
from inventory_pages import build_inventory

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'assets/topic-catalog.js'


class Links(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.current = None
        self.links = []

    def handle_starttag(self, tag, attrs):
        if tag == 'a' and self.current is None:
            href = dict(attrs).get('href')
            if href:
                self.current = [href, []]

    def handle_data(self, data):
        if self.current is not None:
            self.current[1].append(data)

    def handle_endtag(self, tag):
        if tag == 'a' and self.current is not None:
            href, text = self.current
            self.links.append((href, ' '.join(''.join(text).split())))
            self.current = None


def build_catalog(root):
    root = root.resolve()
    inventory = build_inventory(root)
    pages = {p['path']: p for p in inventory['pages']
             if p['kind'] == 'topic' and p['subject'] and p['stage']}
    aliases = {path: set() for path in pages}
    for navigation in (p for p in inventory['pages'] if p['kind'] == 'navigation'):
        source = root / navigation['path']
        parser = Links()
        parser.feed(source.read_text(encoding='utf-8'))
        for href, text in parser.links:
            url = urlsplit(href)
            if url.scheme or url.netloc or not url.path:
                continue
            decoded = unquote(url.path)
            target = (root / decoded.lstrip('/') if decoded.startswith('/') else source.parent / decoded).resolve()
            if target.is_dir():
                target /= 'index.html'
            try:
                relative = target.relative_to(root).as_posix()
            except ValueError:
                continue
            if relative in aliases and text:
                aliases[relative].add(text)
    return [{'path': path, 'title': page['title'], 'subject': page['subject'],
             'stage': page['stage'], 'aliases': sorted(aliases[path])}
            for path, page in pages.items()]


def render(root):
    return ('// Generated by scripts/build_topic_catalog.py; do not edit by hand.\n'
            'window.KV_TOPIC_CATALOG = ' + json.dumps(build_catalog(root), ensure_ascii=False, separators=(',', ':')) + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT, help='site root (defaults to repository)')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--output', type=Path, help='write catalog to this file')
    mode.add_argument('--check', type=Path, help='fail if this file is out of date')
    args = parser.parse_args()
    output = render(args.root)
    if args.check:
        try:
            actual = args.check.read_text(encoding='utf-8')
        except OSError as exc:
            print(f'Cannot read topic catalog: {exc}', file=sys.stderr)
            return 1
        if actual != output:
            print(f'Topic catalog is stale: {args.check}', file=sys.stderr)
            return 1
        print(f'Topic catalog is current: {args.check}')
    else:
        (args.output or OUTPUT).write_text(output, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
